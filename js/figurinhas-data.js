export function figureImagePath(file) {
  return `figures/${encodeURIComponent(file)}`;
}

export function figureThumbPath(file) {
  const webpFile = file.replace(/\.[^.]+$/, ".webp");
  return `figures/thumbs/${encodeURIComponent(webpFile)}`;
}

function normalizar(texto) {
  return (texto || "")
    .toLowerCase()
    .normalize("NFD")
    .replace(/[\u0300-\u036f]/g, "")
    .replace(/\s+/g, " ")
    .trim();
}

/**
 * Tenta achar a figurinha correspondente a um nome digitado livremente.
 * Primeiro por igualdade normalizada; depois por primeiro nome.
 */
export function findFigureByName(nome) {
  const alvo = normalizar(nome);
  if (!alvo) return null;

  const exato = FIGURINHAS.find((f) => normalizar(f.nome) === alvo);
  if (exato) return exato;

  const primeiro = alvo.split(" ")[0];
  return (
    FIGURINHAS.find((f) => normalizar(f.nome).split(" ")[0] === primeiro) || null
  );
}
